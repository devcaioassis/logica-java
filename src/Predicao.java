public class Predicao {
    public static void main(String[] args) {
        int a = 7;
        int b = 3;

        String titulo = "Resultado: ";
        System.out.println(titulo + a + b);
        System.out.println(titulo + (a + b));
        System.out.println(a / b);
        System.out.println(a + b + " é a soma");
    }
}
